// Writes supabase/live/setup.sql: every migration and the Template in one
// transaction, to paste into the live project's SQL Editor once. It stops if
// the crm schema is already there, and undoes everything if any other schema
// would end up different.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "supabase");
const migrations = readdirSync(join(root, "migrations"))
  .filter((name) => name.endsWith(".sql"))
  .sort();
const read = (...path) => readFileSync(join(root, ...path), "utf8").replaceAll("\r\n", "\n").trim();

const OTHER_SCHEMAS = "n.nspname !~ '^pg_' and n.nspname not in ('information_schema', 'crm', 'cron')";

// One short value for everything outside crm: its tables, columns, functions,
// policies and who may use them.
const FINGERPRINT = `
  select md5(coalesce(string_agg(line, chr(10) order by line), '')) as print from (
    select concat_ws('|', 'schema', n.nspname, n.nspacl::text) as line from pg_namespace n where ${OTHER_SCHEMAS}
    union all
    select concat_ws('|', 'relation', n.nspname, c.relname, c.relkind, c.relrowsecurity, c.relacl::text)
      from pg_class c join pg_namespace n on n.oid = c.relnamespace where ${OTHER_SCHEMAS}
    union all
    select concat_ws('|', 'column', a.attrelid, a.attname, a.atttypid, a.attacl::text)
      from pg_attribute a join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace
     where a.attnum > 0 and ${OTHER_SCHEMAS}
    union all
    select concat_ws('|', 'function', f.oid, f.proacl::text, md5(f.prosrc))
      from pg_proc f join pg_namespace n on n.oid = f.pronamespace where ${OTHER_SCHEMAS}
    union all
    select concat_ws('|', 'policy', n.nspname, p.tablename, p.policyname, p.roles::text, p.cmd, p.qual, p.with_check)
      from pg_policies p join pg_namespace n on n.nspname = p.schemaname where ${OTHER_SCHEMAS}
  ) everything_else`;

const sql = `-- Generated by scripts/build-live-sql.mjs. Don't edit this; run that again instead.
begin;

do $go_live$
begin
  if to_regnamespace('crm') is not null then
    raise exception 'The crm schema is already there. Nothing was changed.';
  end if;
  if not exists (select 1 from pg_extension where extname = 'pg_cron') then
    raise exception 'pg_cron is not enabled yet. Nothing was changed.';
  end if;
end;
$go_live$;

create temp table go_live_before on commit drop as ${FINGERPRINT};

${[...migrations.map((name) => ["migrations", name]), ["seeds", "template.sql"]]
  .map((path) => `-- ======== ${path.join("/")} ========\n\n${read(...path)}\n`)
  .join("\n")}
do $go_live$
begin
  if (select b.print from go_live_before b) is distinct from (select a.print from (${FINGERPRINT}) a) then
    raise exception 'Something outside crm would have changed. Everything was undone.';
  end if;
end;
$go_live$;

commit;

select 'Done: crm is set up.' as result;
`;

writeFileSync(join(root, "live", "setup.sql"), sql);
console.log(`Wrote supabase/live/setup.sql: ${migrations.length} migrations and the Template, ${Math.round(sql.length / 1024)} KB.`);
